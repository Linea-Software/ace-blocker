//! Helpers for the `aceblocker://` protocol delivery.
//!
//! The Ace Blocker website hands the desktop-app API key to the engine by
//! pointing the OS at an `aceblocker://` URL. To keep the key out of query
//! strings (they land in process args, engine logs and HTTP access logs),
//! the website places the parameters in the URL **fragment**
//! (`aceblocker://account/api-key#apiKey=...&callback=...`). Fragments are
//! never sent over HTTP, so the protocol handler parses them here and
//! forwards the key via a typed, capability-authenticated remoc RPC call.
//!
//! # Security boundary
//!
//! The OS invokes the protocol handler (`ace-redirect.exe` in release,
//! `ace-engine.exe` in debug) with the full URI in its argv. The handler
//! then forwards a **capability-token-authenticated** `setApiKey` RPC call
//! over the local engine pipe/socket. Any website can render an `aceblocker://` link (the browser
//! asks the user to confirm opening the app once), so the forwarded path is
//! restricted to an explicit allowlist here — a malicious
//! `aceblocker://system/shutdown` link must never turn into an
//! authenticated engine request. The legacy `get-engine-port` deep-link
//! probe has no equivalent privileged engine operation.

use std::collections::HashMap;

/// The only engine routes the protocol handler may forward. Today the
/// product needs exactly one: API-key delivery (`aceblocker://account/api-key`).
/// The deep link is generated by `ace-blocker-site/src/lib/utils.ts`
/// (`aceblocker://account/api-key#apiKey=...&callback=...`).
pub const ALLOWED_FORWARD_PATHS: &[&str] = &["/account/api-key"];

/// A validated protocol-handler forward: an engine-relative path plus an
/// optional (legacy) `apiKey` query string. Only paths produced by
/// [`resolve_forward_target`] may be forwarded with the capability token.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForwardRequest {
    /// Engine-relative path, starting with `/` (error.g. `/account/api-key`).
    pub path: String,
    /// Raw legacy query string without the leading `?` (only ever the
    /// re-encoded `apiKey=<value>` pair), when the URI carried one.
    pub query: Option<String>,
}

/// Why an `aceblocker://` URI was refused forwarding.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProtocolForwardError {
    /// The string is not an `aceblocker://` URI at all.
    NotAProtocolUri,
    /// The path is empty, contains traversal segments (`..`), backslashes,
    /// percent-encoding, repeated/trailing slashes, or other malformed
    /// characters.
    MalformedPath,
    /// The path is well-formed but not on [`ALLOWED_FORWARD_PATHS`].
    PathNotAllowed,
    /// The query string is not exactly the legacy `apiKey=<value>` pair.
    MalformedQuery,
}

impl std::fmt::Display for ProtocolForwardError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProtocolForwardError::NotAProtocolUri => {
                write!(f, "not an aceblocker:// URI")
            }
            ProtocolForwardError::MalformedPath => write!(
                f,
                "malformed path: only plain '/'-separated segments without '..', '\\', '%' or empty segments are allowed"
            ),
            ProtocolForwardError::PathNotAllowed => write!(
                f,
                "path is not in the forward allowlist ({})",
                ALLOWED_FORWARD_PATHS.join(", ")
            ),
            ProtocolForwardError::MalformedQuery => write!(
                f,
                "malformed query string: only the legacy 'apiKey=<value>' parameter is accepted"
            ),
        }
    }
}

/// Parses and validates an `aceblocker://` URI for forwarding to the engine.
///
/// The fragment is ignored for routing (it carries the API key, which is
/// forwarded as a JSON body instead). The path is validated against
/// [`ALLOWED_FORWARD_PATHS`] with strict traversal/malformation checks, and
/// any query string must be exactly the legacy `apiKey=<value>` pair.
///
/// Returns a normalized [`ForwardRequest`] whose `path` always starts with
/// `/` and whose `query` (when present) is re-encoded from the parsed
/// parameter, so nothing unexpected can reach the engine URL.
pub fn resolve_forward_target(uri: &str) -> Result<ForwardRequest, ProtocolForwardError> {
    let rest = uri
        .strip_prefix("aceblocker://")
        .ok_or(ProtocolForwardError::NotAProtocolUri)?;

    // Drop the fragment: `aceblocker://account/api-key#apiKey=...` — the
    // fragment never travels over HTTP and is consumed separately by
    // `api_key_from_fragment`. A raw `#` cannot appear twice (it would have
    // to be percent-encoded), so refuse the URI if it does.
    if rest.matches('#').count() > 1 {
        return Err(ProtocolForwardError::MalformedPath);
    }
    let before_fragment = rest.split('#').next().unwrap_or(rest);

    let (raw_path, raw_query) = match before_fragment.split_once('?') {
        Some((path, query)) => (path, Some(query)),
        None => (before_fragment, None),
    };

    // The URI is `aceblocker://account/api-key` — the first path character
    // must not be `/` (that would be `aceblocker:///...`), and the path
    // must not be empty.
    if raw_path.is_empty() || raw_path.starts_with('/') {
        return Err(ProtocolForwardError::MalformedPath);
    }

    // Segment-level validation: no empty segments (`//`, trailing `/`), no
    // `.`/`..` traversal, no backslashes, no percent-encoding, no control
    // characters. Anything else is refused before the allowlist check so the
    // token can never ride along a path that resolves differently than it
    // reads.
    for segment in raw_path.split('/') {
        if segment.is_empty()
            || segment == "."
            || segment == ".."
            || segment.contains('\\')
            || segment.contains('%')
            || segment.chars().any(char::is_control)
        {
            return Err(ProtocolForwardError::MalformedPath);
        }
    }

    let normalized_path = format!("/{raw_path}");
    if !ALLOWED_FORWARD_PATHS.contains(&normalized_path.as_str()) {
        return Err(ProtocolForwardError::PathNotAllowed);
    }

    // Legacy `?apiKey=` delivery: accept only exactly that single parameter.
    // Anything else is refused rather than forwarded to the engine.
    let query = match raw_query {
        None => None,
        Some(raw_query) => {
            let pairs: Vec<(String, String)> = url::form_urlencoded::parse(raw_query.as_bytes())
                .into_owned()
                .collect();
            let mut api_key_value = None;
            for (key, value) in &pairs {
                if key != "apiKey" {
                    // Any non-apiKey parameter is refused.
                    return Err(ProtocolForwardError::MalformedQuery);
                }
                if api_key_value.is_some() {
                    // Duplicate apiKey parameters are refused.
                    return Err(ProtocolForwardError::MalformedQuery);
                }
                api_key_value = Some(value.clone());
            }
            match api_key_value {
                Some(api_key) if !api_key.is_empty() && !api_key.chars().any(char::is_control) => {
                    let mut encoded = String::new();
                    url::form_urlencoded::Serializer::new(&mut encoded)
                        .append_pair("apiKey", &api_key)
                        .finish();
                    Some(encoded)
                }
                _ => return Err(ProtocolForwardError::MalformedQuery),
            }
        }
    };

    Ok(ForwardRequest {
        path: normalized_path,
        query,
    })
}

/// Parse `application/x-www-form-urlencoded`-style parameters out of a URL
/// fragment (error.g. `apiKey=abc&callback=...` -> `{"apiKey": "abc", ...}`).
pub fn parse_fragment_params(fragment: &str) -> HashMap<String, String> {
    url::form_urlencoded::parse(fragment.as_bytes())
        .into_owned()
        .collect()
}

/// Extract the `apiKey` parameter delivered via a protocol URL fragment.
pub fn api_key_from_fragment(fragment: Option<&str>) -> Option<String> {
    fragment.and_then(|fragment| parse_fragment_params(fragment).get("apiKey").cloned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_key_and_callback_from_fragment() {
        let params = parse_fragment_params(
            "apiKey=abc123&callback=%2Fcheckout%2Fcompleted%3Factivated%3Dtrue",
        );
        assert_eq!(params.get("apiKey").map(String::as_str), Some("abc123"));
        assert_eq!(
            params.get("callback").map(String::as_str),
            Some("/checkout/completed?activated=true")
        );
    }

    #[test]
    fn missing_key_returns_none() {
        assert_eq!(api_key_from_fragment(None), None);
        assert_eq!(api_key_from_fragment(Some("callback=%2Fhome")), None);
        assert_eq!(
            api_key_from_fragment(Some("apiKey=secret")),
            Some("secret".to_string())
        );
    }

    // ── resolve_forward_target: the product deep link ──────────────────

    #[test]
    fn allows_the_account_api_key_route_with_fragment() {
        // The exact link generated by ace-blocker-site/src/lib/utils.ts.
        let request = resolve_forward_target(
            "aceblocker://account/api-key#apiKey=abc123&callback=%2Fcheckout",
        )
        .expect("the product deep link must be allowed");
        assert_eq!(request.path, "/account/api-key");
        assert_eq!(request.query, None);
    }

    #[test]
    fn allows_the_legacy_api_key_query_parameter() {
        let request = resolve_forward_target("aceblocker://account/api-key?apiKey=abc123")
            .expect("legacy query delivery must stay supported");
        assert_eq!(request.path, "/account/api-key");
        assert_eq!(request.query, Some("apiKey=abc123".to_string()));
    }

    // ── resolve_forward_target: rejections ─────────────────────────────

    #[test]
    fn rejects_state_changing_routes() {
        for uri in [
            "aceblocker://system/shutdown",
            "aceblocker://system/update/content",
            "aceblocker://backup/import",
            "aceblocker://network-blocks",
            "aceblocker://network-blocks/1234-5678",
            "aceblocker://network-blocks/1234-5678/schedule",
            "aceblocker://account/logout",
            "aceblocker://account/api-key/extra",
            "aceblocker://account/api-key-other",
            "aceblocker://ACCOUNT/api-key",
            "aceblocker://dev/usage",
        ] {
            assert_eq!(
                resolve_forward_target(uri),
                Err(ProtocolForwardError::PathNotAllowed),
                "{uri} must be rejected as not allowed"
            );
        }
    }

    #[test]
    fn rejects_path_traversal_and_malformed_paths() {
        for uri in [
            "aceblocker://account/api-key/../system/shutdown",
            "aceblocker://account/../system/shutdown",
            "aceblocker://../system/shutdown",
            "aceblocker://account/api-key/%2e%2e/system/shutdown",
            "aceblocker://account/api-key/..%2fsystem/shutdown",
            "aceblocker://account\\api-key",
            "aceblocker://account/api-key//",
            "aceblocker://account//api-key",
            "aceblocker://account/api-key/",
            "aceblocker:///account/api-key",
            "aceblocker://./account/api-key",
            "aceblocker://",
            "aceblocker://?apiKey=abc",
            "aceblocker://account/api-key#frag#extra",
        ] {
            let result = resolve_forward_target(uri);
            assert!(
                matches!(
                    result,
                    Err(ProtocolForwardError::MalformedPath)
                        | Err(ProtocolForwardError::PathNotAllowed)
                ),
                "{uri} must be rejected as malformed or not allowed, got {result:?}"
            );
        }
    }

    #[test]
    fn rejects_non_protocol_uris() {
        assert_eq!(
            resolve_forward_target("https://aceblocker.com/account/api-key"),
            Err(ProtocolForwardError::NotAProtocolUri)
        );
        assert_eq!(
            resolve_forward_target("account/api-key"),
            Err(ProtocolForwardError::NotAProtocolUri)
        );
        assert_eq!(
            resolve_forward_target(""),
            Err(ProtocolForwardError::NotAProtocolUri)
        );
    }

    #[test]
    fn rejects_malformed_or_unknown_query_strings() {
        for uri in [
            "aceblocker://account/api-key?apiKey=",
            "aceblocker://account/api-key?apiKey=abc&callback=%2Fhome",
            "aceblocker://account/api-key?other=abc",
            "aceblocker://account/api-key?apiKey=abc&apiKey=def",
            "aceblocker://account/api-key?apiKey=a%00b",
        ] {
            assert_eq!(
                resolve_forward_target(uri),
                Err(ProtocolForwardError::MalformedQuery),
                "{uri} must be rejected as a malformed query"
            );
        }
    }
}
